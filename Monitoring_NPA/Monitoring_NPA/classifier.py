    def _matches_exclude_patterns(cls, title_lower: str, patterns: List[str]) -> bool:
        """Проверяет, соответствует ли заголовок паттернам исключения для конкретной категории"""
        for pattern in patterns:
            if re.search(pattern, title_lower):
                return True
        return False


    @classmethod
    def classify(cls, text: str) -> Set[str]:
        if not text:
            return set()

        text_lower = text.lower()
        found_topics = set()

        for topic, keywords in cls.KEYWORDS.items():

            # Проверяем исключения
            exclude_patterns = cls.EXCLUDE_PATTERNS.get(topic, [])
            for exclude in exclude_patterns:
                if cls._matches(text_lower, exclude):
                    break
            else:
                # Проверяем ключевые слова
                for keyword in keywords:
                    if cls._matches(text_lower, keyword):
                        found_topics.add(topic)
                        break

        return found_topics


    @classmethod
    def get_topic_name(cls, topic_code: str) -> str:
        names = {
            'kedo': '👥 КЭДО',
            'mchd': '📄 МЧД',
            'epd': '🚛 ЭПД',
            'ep': '✍️ ЭП',
            'ofd': '🧾 ОФД',
            'reporting': '📊 Отчетность',
            'edo_b2b': '🔄 B2B ЭДО',
            'ecosystem': '🌐 Экосистема/ПД'
        }
        return names.get(topic_code, topic_code)


    @classmethod
    def format_topics(cls, topics: Set[str]) -> str:
        if not topics:
            return '❓ Не определена'
        return ' '.join([cls.get_topic_name(t) for t in topics])


    @classmethod
    def classify_with_confidence(cls, title: str) -> Dict[str, Set[str]]:

        if not title:
            return {'topics': set(), 'excluded': set()}

        title_lower = title.lower()
        found_topics = set()
        excluded_topics = set()

        # Проверяем исключения
        for topic, patterns in cls.EXCLUDE_PATTERNS.items():
            for pattern in patterns:
                if cls._matches(title_lower, pattern):
                    excluded_topics.add(topic)
                    break

        # Проверяем ключевые слова
        for topic, keywords in cls.KEYWORDS.items():
            if topic in excluded_topics:
                continue

            for keyword in keywords:
                if cls._matches(title_lower, keyword):
                    found_topics.add(topic)
                    break

        return {
            'topics': found_topics,
            'excluded': excluded_topics
        }

    @classmethod
    def classify_as_list(cls, title: str) -> List[str]:
        topics_set = cls.classify(title)
        return list(topics_set)

    @staticmethod
    def _is_regex(pattern: str) -> bool:
        regex_symbols = r".*+?[](){}|\^$\\"
        return any(symbol in pattern for symbol in regex_symbols)

    @classmethod
    def _matches(cls, text: str, phrase: str) -> bool:
        if re.search(r'\d|№|@|-|/', phrase):
            return phrase.lower() in text

        if any(ch in phrase for ch in r".*+?[](){}|\^$\\"):
            return re.search(phrase, text, re.IGNORECASE) is not None

        morph_pattern = cls._make_morph_pattern(phrase)

        return re.search(morph_pattern, text, re.IGNORECASE) is not None
    @staticmethod
    def _make_morph_pattern(phrase: str) -> str:
        words = phrase.lower().strip().split()
        pattern_words = []

        for word in words:
            if re.search(r'\d|№|@|-|/', word):
                pattern_words.append(re.escape(word.lower()))
            else:
                base = word[:-2] if len(word) > 4 else word
                pattern_words.append(f"{re.escape(base)}[а-я]*")

        return r"\s+".join(pattern_words)